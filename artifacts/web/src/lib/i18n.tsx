const DICT: Record<Lang, Record<Key, string>> = { ru, en };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = DICT[lang][key] ?? DICT.ru[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

const Ctx = createContext<Lang>("ru");
export const LangProvider = ({ lang, children }: { lang: Lang; children: ReactNode }) => <Ctx.Provider value={lang}>{children}</Ctx.Provider>;
export function useT() {
  const lang = useContext(Ctx);
  return Object.assign((key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars), { lang });
}

export const browserLang = (): Lang => (navigator.language?.toLowerCase().startsWith("ru") ? "ru" : "en");
